using PKHeX.Core;
using SysBot.Base;
using System;
using System.Diagnostics;
using System.Threading;
using System.Threading.Tasks;

namespace SysBot.Pokemon.Helpers;

/// <summary>
/// Legends: Z-A (PA9) custom-IV support.
/// </summary>
/// <remarks>
/// Z-A encounters derive EC → PID → IVs → ability → gender → nature → scale from a single Xoroshiro seed, and
/// PKHeX's legality check recovers that seed from EC/PID and re-verifies the IVs. Writing IVs directly onto the
/// entity therefore breaks the correlation and is flagged illegal (which is why the generic post-generation IV
/// re-application reverts for Z-A). PKHeX's own generator only tries 100k seeds before dropping the IV request.
/// <para>
/// This helper searches for a seed (in parallel) that produces the requested IVs. A requested 31 is satisfied by
/// Hyper Training when the level allows it (Lv50+ in Z-A), so only the non-31 values have to come from the seed —
/// e.g. 12/31/12/31/31/4 needs just HP/Def/Spe (~2^15 seeds), which resolves in milliseconds.
/// </para>
/// </remarks>
public static class ZAIVSeedSearch
{
    /// <summary>Total wall-clock budget for a single request.</summary>
    public static TimeSpan SearchBudget { get; set; } = TimeSpan.FromSeconds(10);

    /// <summary>Share of the budget spent trying to also hit the requested nature from the seed before falling back to a mint.</summary>
    private const double NatureAttemptShare = 0.35;

    private const int RandomIV = -1;

    /// <summary>Upper bound (log2 of expected seeds) worth attempting within <see cref="SearchBudget"/>.</summary>
    private const double MaxLog2Cost = 31;

    /// <summary>
    /// Re-rolls the correlated data of <paramref name="pk"/> so its IVs satisfy <paramref name="requestedIVs"/>.
    /// </summary>
    /// <param name="pk">Legal Z-A entity generated by ALM. Only replaced when the result is legal.</param>
    /// <param name="requestedIVs">Requested IVs in PKHeX order (HP/Atk/Def/Spe/SpA/SpD), e.g. <see cref="ShowdownSet.IVs"/>. Values outside 0-31 are treated as "don't care".</param>
    /// <param name="requestedNature">Requested nature, or <see cref="Nature.Random"/> for none.</param>
    /// <param name="allowHyperTraining">False when the user asked for no Hyper Training ("Hypertrain: False"); requested 31s must then come from the seed.</param>
    /// <returns><see langword="true"/> if <paramref name="pk"/> was updated to match the request.</returns>
    public static bool TryApplyRequestedIVs(ref PA9 pk, ReadOnlySpan<int> requestedIVs, Nature requestedNature = Nature.Random, bool allowHyperTraining = true)
    {
        if (requestedIVs.Length != 6)
            return false;

        Span<int> want = stackalloc int[6];
        for (int i = 0; i < 6; i++)
            want[i] = requestedIVs[i] is >= 0 and <= 31 ? requestedIVs[i] : RandomIV;

        // Nothing but 31s requested: ALM's Hyper Training already covers that, and a raw 6x31 seed is a ~2^30 search.
        bool anyNon31 = false;
        foreach (var v in want)
            anyNon31 |= v is not (31 or RandomIV);
        if (!anyNon31)
            return false;

        if (IsSatisfied(pk, want))
            return false;

        var la = new LegalityAnalysis(pk);
        if (!la.Valid || la.EncounterOriginal is not IEncounter9a enc)
            return false; // HOME-transferred / non-native: IVs aren't Z-A seed correlated; the generic re-application handles those.

        var pi = PersonalTable.ZA[enc.Species, enc.Form];
        bool shiny = pk.IsShiny;
        var param = enc switch
        {
            EncounterSlot9a s => s.GetParams(pi, shiny, shiny),
            EncounterStatic9a s => s.GetParams(pi, shiny, shiny),
            _ => enc.GetParams(pi),
        };

        if (param.IVs.IsSpecified)
        {
            LogUtil.LogInfo($"{(Species)pk.Species}: encounter has fixed IVs; custom IVs cannot be applied.", nameof(ZAIVSeedSearch));
            return false;
        }

        bool canHyperTrain = allowHyperTraining && pk.CurrentLevel >= 50; // Z-A Hyper Training minimum level (same as SV)

        // Seed-bound IVs: every requested non-31. Requested 31s are Hyper Trained (Lv50+).
        // Below Lv50 a 31 must also come from the seed; that's only attempted when the total stays cheap
        // (<= 4 bound stats ≈ 2^20 seeds), otherwise the non-31s are honored and the rest stay as rolled.
        Span<int> hard = stackalloc int[6];
        Span<int> strict = stackalloc int[6];
        int hardCount = 0, strictCount = 0;
        for (int i = 0; i < 6; i++)
        {
            hard[i] = want[i] is not (31 or RandomIV) ? want[i] : RandomIV;
            strict[i] = want[i];
            if (hard[i] != RandomIV) hardCount++;
            if (strict[i] != RandomIV) strictCount++;
        }

        // Expected seeds ≈ 32^boundStats (× ~585 for a random shiny with charm rolls). Skip hopeless requests outright
        // instead of tying up the queue for the whole budget.
        double log2Cost = (5 * hardCount) + (shiny && param.Shiny is Shiny.Random ? 9.2 : 0);
        if (log2Cost > MaxLog2Cost)
        {
            LogUtil.LogInfo($"{(Species)pk.Species}: IVs {Format(want)} need ~2^{log2Cost:0} seeds{(shiny ? " (shiny)" : "")}; too many to search, keeping generated IVs.", nameof(ZAIVSeedSearch));
            return false;
        }

        var shinyType = shiny ? Shiny.Always : Shiny.Never;
        var gender = pk.Gender switch { 0 => Gender.Male, 1 => Gender.Female, _ => Gender.Random };
        var baseCriteria = MakeCriteria(hard, shinyType, gender);

        var sw = Stopwatch.StartNew();
        var original = pk;
        int abilityNumber = pk.AbilityNumber;
        PA9? seed = null; // the entity generated from the winning seed
        bool natureWanted = requestedNature is not Nature.Random && requestedNature <= Nature.Quirky && param.Nature > Nature.Quirky; // not fixed by the encounter
        var natureBudget = TimeSpan.FromTicks((long)(SearchBudget.Ticks * NatureAttemptShare));

        // 0) Below Lv50: try to get the requested 31s from the seed as well, when that's affordable.
        if (!canHyperTrain && strictCount > hardCount && strictCount <= 4)
        {
            var strictCriteria = MakeCriteria(strict, shinyType, gender);
            if (natureWanted)
                seed = Search(original, param, strictCriteria with { Nature = requestedNature }, abilityNumber, natureBudget);
            seed ??= Search(original, param, strictCriteria, abilityNumber, natureBudget);
        }

        // 1) Try to hit the requested nature straight from the seed (no mint needed).
        if (seed is null && natureWanted)
            seed ??= Search(original, param, baseCriteria with { Nature = requestedNature }, abilityNumber, natureBudget);

        // 2) Otherwise any nature; the nature gets minted afterwards.
        seed ??= Search(original, param, baseCriteria, abilityNumber, SearchBudget - sw.Elapsed);

        if (seed is not { } generated)
        {
            LogUtil.LogInfo($"{(Species)pk.Species}: no seed found for IVs {Format(want)} ({hardCount} seed-bound stats) within {sw.Elapsed.TotalSeconds:0.0}s.", nameof(ZAIVSeedSearch));
            return false;
        }

        // Use the worker's entity as-is: Alpha flawless-IV placement draws from Util.Rand (not the seed),
        // so regenerating from the seed alone would not reproduce the same IVs.
        var result = generated;

        // Hyper Train (Lv50+) the requested 31s the seed didn't roll as 31; never flag a stat that is already 31.
        result.HT_HP  = canHyperTrain && want[0] == 31 && result.IV_HP  != 31;
        result.HT_ATK = canHyperTrain && want[1] == 31 && result.IV_ATK != 31;
        result.HT_DEF = canHyperTrain && want[2] == 31 && result.IV_DEF != 31;
        result.HT_SPE = canHyperTrain && want[3] == 31 && result.IV_SPE != 31;
        result.HT_SPA = canHyperTrain && want[4] == 31 && result.IV_SPA != 31;
        result.HT_SPD = canHyperTrain && want[5] == 31 && result.IV_SPD != 31;

        // Keep a mint the original had; otherwise mint to the requested nature if the seed nature differs.
        if (requestedNature is not Nature.Random && requestedNature <= Nature.Quirky && result.Nature != requestedNature)
            result.StatAlignment = requestedNature;
        else if (original.StatAlignment != original.Nature && result.Nature == original.Nature)
            result.StatAlignment = original.StatAlignment;

        result.ResetPartyStats();
        result.RefreshChecksum();

        var la2 = new LegalityAnalysis(result);
        if (!la2.Valid && result.StatAlignment != result.Nature)
        {
            // Mint rejected for this encounter — keep the seed's nature.
            result.StatAlignment = result.Nature;
            result.RefreshChecksum();
            la2 = new LegalityAnalysis(result);
        }

        if (!la2.Valid)
        {
            LogUtil.LogInfo($"{(Species)pk.Species}: seed (EC {result.EncryptionConstant:X8}) matched IVs but failed legality:\n{la2.Report()}", nameof(ZAIVSeedSearch));
            return false;
        }

        LogUtil.LogInfo($"{(Species)pk.Species}: applied IVs {Format(want)} via seed (EC {result.EncryptionConstant:X8}) in {sw.Elapsed.TotalMilliseconds:0}ms (Nature {result.Nature}, Stat Nature {result.StatAlignment}).", nameof(ZAIVSeedSearch));
        pk = result;
        return true;
    }

    private static EncounterCriteria MakeCriteria(ReadOnlySpan<int> ivs, Shiny shiny, Gender gender) => EncounterCriteria.Unrestricted with
    {
        IV_HP = (sbyte)ivs[0], IV_ATK = (sbyte)ivs[1], IV_DEF = (sbyte)ivs[2],
        IV_SPE = (sbyte)ivs[3], IV_SPA = (sbyte)ivs[4], IV_SPD = (sbyte)ivs[5],
        Shiny = shiny,
        Gender = gender,
    };

    private static PA9? Search(PA9 template, GenerateParam9a param, EncounterCriteria criteria, int abilityNumber, TimeSpan budget)
    {
        if (budget <= TimeSpan.Zero)
            return null;

        long deadline = Stopwatch.GetTimestamp() + (long)(budget.TotalSeconds * Stopwatch.Frequency);
        long found = 0;
        PA9? result = null;
        int workers = Math.Max(1, Environment.ProcessorCount - 1);

        Parallel.For(0, workers, new ParallelOptions { MaxDegreeOfParallelism = workers }, _ =>
        {
            var pk = (PA9)template.Clone();
            var rand = new Xoroshiro128Plus(Util.Rand.Rand64());
            int ctr = 0;
            while (Interlocked.Read(ref found) == 0)
            {
                // Checking the clock every iteration is comparatively expensive; batch it.
                if ((++ctr & 0xFFF) == 0 && Stopwatch.GetTimestamp() > deadline)
                    return;

                ulong seed = rand.Next();
                if (!LumioseRNG.GenerateData(pk, param, criteria, seed))
                    continue;
                if (pk.AbilityNumber != abilityNumber)
                    continue;

                if (Interlocked.CompareExchange(ref found, 1, 0) == 0)
                    result = pk;
                return;
            }
        });

        return Interlocked.Read(ref found) != 0 ? result : null;
    }

    private static bool IsSatisfied(PA9 pk, ReadOnlySpan<int> want)
    {
        Span<int> ivs = stackalloc int[6];
        pk.GetIVs(ivs);
        Span<bool> ht = [pk.HT_HP, pk.HT_ATK, pk.HT_DEF, pk.HT_SPE, pk.HT_SPA, pk.HT_SPD];
        for (int i = 0; i < 6; i++)
        {
            if (want[i] == RandomIV)
                continue;
            int effective = ht[i] ? 31 : ivs[i];
            if (effective != want[i] || (want[i] != 31 && ht[i]))
                return false;
        }
        return true;
    }

    // Showdown display order: HP/Atk/Def/SpA/SpD/Spe
    private static string Format(ReadOnlySpan<int> v) =>
        $"{Fmt(v[0])}/{Fmt(v[1])}/{Fmt(v[2])}/{Fmt(v[4])}/{Fmt(v[5])}/{Fmt(v[3])}";

    private static string Fmt(int v) => v == RandomIV ? "x" : v.ToString();
}
